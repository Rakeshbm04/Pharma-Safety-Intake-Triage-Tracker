"""Scripted capstone walkthrough -> docs/DEMO_EVIDENCE.md

Demonstrates, on a fresh temporary database with FICTIONAL data:
  1. two fictional reports (AE + PQC) incl. a rejected invalid intake
  2. status transitions incl. the HITL closure gate (freeze, four-eyes approval)
  3. a multi-stage hybrid RAG query with per-stage results
  4. agent control plane: router intents, auto-repair, guardrail refusal, circuit breaker
  5. the append-only audit trail and the PostToolUse hook log

    python scripts/demo_walkthrough.py [--backend auto|neural|offline]
"""
from __future__ import annotations

import argparse
import json
import sqlite3
import sys
import tempfile
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app import audit, config, workflow  # noqa: E402
from app.agent.orchestrator import Orchestrator  # noqa: E402
from app.models import Actor, Role, Status  # noqa: E402
from app.rag.service import KnowledgeBase  # noqa: E402
from app.repository import DuplicateSubmissionError, ReportRepository  # noqa: E402
from app.validation import validate_intake  # noqa: E402
from scripts.seed_demo import seed  # noqa: E402

OUT = ROOT / "docs" / "DEMO_EVIDENCE.md"
OPERATOR = Actor(actor_id="OP-01", role=Role.OPERATOR)
REVIEWER = Actor(actor_id="OP-07", role=Role.REVIEWER)


def d(n: int) -> str:
    return (date.today() - timedelta(days=n)).isoformat()


class Doc:
    def __init__(self):
        self.lines: list[str] = []

    def h(self, level: int, text: str):
        self.lines += ["", "#" * level + " " + text, ""]

    def p(self, text: str = ""):
        self.lines.append(text)

    def code(self, text: str, lang: str = ""):
        self.lines += [f"```{lang}", text, "```"]

    def table(self, headers: list[str], rows: list[list]):
        self.lines.append("| " + " | ".join(headers) + " |")
        self.lines.append("|" + "---|" * len(headers))
        for r in rows:
            self.lines.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |")
        self.lines.append("")


def stage_rows(hits, n=8, extra=None):
    return [[h.rank, h.source_id, h.chunk_id, f"{h.score:.4f}"] + ([h.extra.get(extra)] if extra else []) for h in hits[:n]]


def main(backend: str) -> None:
    tmp = Path(tempfile.mkdtemp(prefix="pharma_demo_"))
    db = tmp / "demo.db"
    doc = Doc()
    doc.p("# Demonstration Evidence: Pharma Safety Intake & Triage Tracker")
    doc.p(f"_Generated by `scripts/demo_walkthrough.py` on {date.today().isoformat()} against a fresh temporary "
          "database. All products, batches and reports are fictional._")

    # -- background history used by RAG ---------------------------------------
    seed(db)
    repo = ReportRepository(db)

    # -- 1. two new fictional reports --------------------------------------------
    doc.h(2, "1. Intake of two fictional reports")
    bad = {"report_type": "Suspected Adverse Event", "product_name": "Zentrovax 50 mg tablets",
           "batch_number": "LOT-8839", "date_received": d(0), "reporter_type": "Healthcare Professional",
           "description": "Caller jane@example.com reported a reaction."}
    _, errors = validate_intake(bad)
    doc.p("**Rejected attempt.** Missing and invalid fields produce explicit, context-sensitive errors, and nothing is saved:")
    doc.table(["Field", "Error message"], [[e.label, e.message] for e in errors])

    ae = {"report_type": "Suspected Adverse Event", "product_name": "Zentrovax 50 mg tablets",
          "batch_number": "LOT-88392", "date_received": d(1), "reporter_type": "Healthcare Professional",
          "description": "Fictional nurse telephoned about a reaction shortly after a dose from a new pack.",
          "event_description": "Difficulty breathing and wheezing for about thirty minutes after the morning dose.",
          "event_onset_date": d(2)}
    pqc = {"report_type": "Product Quality Complaint", "product_name": "Neurolin 2 mL injection vial",
           "batch_number": "LOT-60218", "date_received": d(0), "reporter_type": "Healthcare Professional",
           "description": "Second vial from the same carton shows visible particulate matter after reconstitution."}
    created = []
    for payload in (ae, pqc):
        model, errs = validate_intake(payload)
        assert not errs, errs
        created.append(repo.create(model, OPERATOR, channel="form"))
    doc.p("**Accepted reports.** Reference IDs are generated automatically:")
    doc.table(["Reference", "Type", "Product", "Batch", "Received", "Status"],
              [[r.ref_id, r.report_type.value, r.product_name, r.batch_number, r.date_received, r.status.value] for r in created])
    ae_ref, pqc_ref = created[0].ref_id, created[1].ref_id
    try:  # operator double-clicks Save on the PQC
        repo.create(validate_intake(pqc)[0], OPERATOR, channel="form")
        dup_msg = "NOT BLOCKED (unexpected)"
    except DuplicateSubmissionError as exc:
        dup_msg = f"blocked: {exc}"
    doc.p(f"**Duplicate submission** (same PQC saved twice) → {dup_msg} Reports in DB: {len(repo.list())}.")

    # -- 2. status transitions + HITL -------------------------------------------
    doc.h(2, "2. Status lifecycle with Human-in-the-Loop closure")
    steps = []
    workflow.change_status(db, ae_ref, Status.IN_REVIEW, OPERATOR)
    steps.append([f"OP-01 moves {ae_ref} New → In Review", "✅ allowed", repo.get(ae_ref).status.value])
    try:
        workflow.change_status(db, ae_ref, Status.NEW, OPERATOR)
    except workflow.TransitionError as exc:
        steps.append([f"OP-01 tries to move {ae_ref} back to New", f"⛔ {exc}", repo.get(ae_ref).status.value])
    try:
        workflow.change_status(db, ae_ref, Status.CLOSED, OPERATOR)
    except workflow.HITLRequiredError as exc:
        steps.append(["OP-01 tries to close directly", f"⛔ {exc}", repo.get(ae_ref).status.value])
    aid = workflow.request_closure(db, ae_ref, OPERATOR)
    steps.append([f"OP-01 submits closure request #{aid}", "⏳ report frozen", repo.get(ae_ref).status.value])
    try:
        workflow.change_status(db, ae_ref, Status.NEW, OPERATOR)
    except workflow.TransitionError as exc:
        steps.append(["OP-01 tries to send it back while pending", f"⛔ {exc}", repo.get(ae_ref).status.value])
    try:
        workflow.approve_closure(db, aid, Actor(actor_id="OP-01", role=Role.REVIEWER))
    except workflow.ApprovalError as exc:
        steps.append(["Requester OP-01 (as reviewer) tries to self-approve", f"⛔ {exc}", repo.get(ae_ref).status.value])
    workflow.approve_closure(db, aid, REVIEWER)
    steps.append([f"Safety Reviewer OP-07 approves #{aid}", "✅ human authorisation recorded", repo.get(ae_ref).status.value])
    doc.table(["Action", "Result", "Status after"], steps)

    # -- 3. multi-stage RAG --------------------------------------------------------
    doc.h(2, "3. Multi-stage hybrid RAG query")
    kb = KnowledgeBase(db, backend=backend)
    pipe = kb.pipeline()
    query = "Have we had reports of patients with difficulty breathing on batch LOT-88392?"
    r = pipe.search(query)
    doc.p(f"**Query:** _{query}_  ")
    doc.p(f"**Backend:** `{r.backend}`  ")
    doc.p(f"**Parameters:** BM25 k1={config.BM25_K1}, b={config.BM25_B}; chunks {config.CHUNK_TOKENS}/{config.CHUNK_OVERLAP} "
          f"overlap; top-{config.RETRIEVER_TOP_N} per retriever; RRF k={config.RRF_K}; rerank threshold "
          f"{config.RERANK_THRESHOLD}; final top-{config.FINAL_TOP_K}.")
    doc.p(f"**Corpus:** {len(pipe.chunks)} chunks ({sum(c.source_type == 'SOP' for c in pipe.chunks)} SOP, "
          f"{sum(c.source_type == 'REPORT' for c in pipe.chunks)} report).")
    doc.h(3, f"Stage 1: BM25 lexical ({len(r.bm25)} candidates)")
    doc.table(["Rank", "Source", "Chunk", "BM25"], stage_rows(r.bm25))
    doc.h(3, f"Stage 2: Bi-encoder dense ({len(r.dense)} candidates)")
    doc.table(["Rank", "Source", "Chunk", "Cosine"], stage_rows(r.dense))
    doc.h(3, f"Stage 3: Reciprocal Rank Fusion ({len(r.fused)} fused)")
    doc.table(["Rank", "Source", "Chunk", "RRF", "Per-stage ranks"], stage_rows(r.fused, extra="ranks"))
    doc.h(3, f"Stage 4: Cross-encoder rerank (threshold {config.RERANK_THRESHOLD}, {len(r.final)} kept)")
    doc.table(["Rank", "Source", "Chunk", "Relevance", "Kept"], stage_rows(r.reranked, extra="kept"))
    doc.h(3, "Grounded, extractive answer")
    doc.p(r.answer)
    neg = pipe.search("What is the weather forecast in Paris tomorrow?")
    doc.p("")
    doc.p(f"**Negative control:** _What is the weather forecast in Paris tomorrow?_ → {len(neg.final)} chunks kept:")
    doc.p(f"> {neg.answer}")

    # -- 4. agent control plane ------------------------------------------------------
    doc.h(2, "4. Agent control plane (router → tools → guardrails → circuit breaker)")
    orch = Orchestrator(db, OPERATOR, rag_provider=kb.pipeline)
    rows = []
    for msg in ["Hello", f"what is the status of ref 2026 {int(pqc_ref[-4:])}",
                f"move {pqc_ref} to in reveiw", f"close {pqc_ref}",
                "Did Zentrovax cause the breathing problem? Should the patient stop taking it?",
                "what does the SOP say about particles in an injection vial"]:
        resp = orch.handle(msg)
        repairs = "; ".join(x for t in resp.tool_results for x in t.repairs) or "-"
        rows.append([msg, resp.intent.value, ", ".join(t.tool for t in resp.tool_results) or "-", repairs,
                     resp.text.split("\n")[0][:140]])
    doc.table(["User message", "Route", "Tool(s)", "Auto-repair", "Response (first line)"], rows)

    doc.p("**ReAct trace (short-term memory) for the last request:**")
    doc.code("\n".join(f"{s.kind:<12}{s.content[:160]}" for s in resp.trace))

    doc.p("**Circuit breaker:** the same invalid call is repeated three times:")
    cb_rows = []
    for i in range(1, 4):
        resp = orch.handle("move REF-2026-0999 to Archivedd")
        cb_rows.append([i, "HALTED" if resp.halted else "error returned", resp.text[:150]])
    doc.table(["Attempt", "Outcome", "Message"], cb_rows)

    # -- 5. audit trail -----------------------------------------------------------------
    doc.h(2, "5. Audit trail (append-only, metadata only)")
    entries = [e for e in reversed(audit.list_entries(db, limit=1000)) if e.ref_id in (ae_ref, pqc_ref) or e.ref_id is None]
    doc.table(["#", "UTC timestamp", "Ref", "Action", "Actor", "Role", "Old", "New", "Metadata"],
              [[e.id, e.ts_utc[:23], e.ref_id or "-", e.action, e.actor_id, e.actor_role, e.old_status or "",
                e.new_status or "", json.dumps(e.metadata)] for e in entries])
    conn = sqlite3.connect(db)
    try:
        conn.execute("DELETE FROM audit_log")
        tamper = "NOT BLOCKED (unexpected)"
    except sqlite3.IntegrityError as exc:
        tamper = f"blocked: `{exc}`"
    conn.close()
    doc.p(f"**Tamper test:** `DELETE FROM audit_log` → {tamper}")
    dump = json.dumps([e.__dict__ for e in audit.list_entries(db, limit=1000)])
    leaked = [t for t in (ae["description"], ae["event_description"], pqc["description"]) if t in dump]
    doc.p(f"**Data-minimisation check:** report/event descriptions found in audit rows: {len(leaked)}")

    # -- 6. hook log ------------------------------------------------------------------------
    doc.h(2, "6. Governance hook log (PostToolUse → logs/agent_edit_audit.jsonl)")
    log = ROOT / "logs" / "agent_edit_audit.jsonl"
    if log.exists():
        lines = [json.loads(l) for l in log.read_text(encoding="utf-8").splitlines() if l.strip()]
        doc.p(f"{len(lines)} file-edit events recorded. Keys present: `{sorted({k for x in lines for k in x})}`. "
              "No content, old/new strings or descriptions are stored. Last 8 events:")
        doc.table(["UTC", "Tool", "File", "Bytes", "Success"],
                  [[x["ts_utc"][:19], x["tool_name"], x["file_path"], x["content_bytes"], x["success"]] for x in lines[-8:]])
    else:
        doc.p("_No hook log found yet._")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(doc.lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--backend", default=config.RAG_BACKEND, choices=["auto", "neural", "offline"])
    main(ap.parse_args().backend)
